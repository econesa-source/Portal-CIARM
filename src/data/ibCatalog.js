/**
 * Computa dinámicamente las facetas disponibles a partir del catálogo
 */
export function computeFacets(catalog = IB_CLASSIFIED_CATALOG) {
  const grupos = [...new Set(catalog.map(c => c.grupo))].sort();
  const materias = [...new Set(catalog.map(c => c.materia))].sort();
  const tipos = [...new Set(catalog.map(c => c.tipo))].sort();
  const vigencias = [...new Set(catalog.map(c => c.vigencia))].sort();
  const idiomas = [...new Set(catalog.map(c => c.idioma))].sort();

  const allTags = catalog.flatMap(c => c.tags || []);
  const tagCounts = allTags.reduce((acc, tag) => {
    acc[tag] = (acc[tag] || 0) + 1;
    return acc;
  }, {});

  const popularTags = Object.entries(tagCounts)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 12)
    .map(([tag]) => tag);

  return {
    grupos,
    materias,
    tipos,
    vigencias,
    idiomas,
    popularTags
  };
}

/**
 * Filtra el catálogo en tiempo real con soporte multifacético
 */
export function filterCatalog(catalog = IB_CLASSIFIED_CATALOG, filters = {}) {
  const {
    query = "",
    grupo = "ALL",
    materia = "ALL",
    tipo = "ALL",
    vigencia = "ALL",
    idioma = "ALL",
    tag = "ALL"
  } = filters;

  const q = query.toLowerCase().trim();

  return catalog.filter(item => {
    const matchQuery = !q ||
      item.titulo.toLowerCase().includes(q) ||
      item.materia.toLowerCase().includes(q) ||
      item.grupo.toLowerCase().includes(q) ||
      item.archivo.toLowerCase().includes(q) ||
      (item.tags && item.tags.some(t => t.toLowerCase().includes(q)));

    const matchGrupo = grupo === "ALL" || item.grupo === grupo || item.grupo.includes(grupo);
    const matchMateria = materia === "ALL" || item.materia === materia;
    const matchTipo = tipo === "ALL" || item.tipo === tipo;
    const matchVigencia = vigencia === "ALL" || item.vigencia.includes(vigencia);
    const matchIdioma = idioma === "ALL" || item.idioma === idioma;
    const matchTag = tag === "ALL" || (item.tags && item.tags.includes(tag));

    return matchQuery && matchGrupo && matchMateria && matchTipo && matchVigencia && matchIdioma && matchTag;
  });
}
